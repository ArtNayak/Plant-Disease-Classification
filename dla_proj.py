def find_split_dir(root, split_name):

    candidates = []

    for current_root, dirs, files in os.walk(root):

        if os.path.basename(current_root).lower() == split_name.lower():

            # Check that this directory contains subdirectories
            subdirs = [
                d for d in os.listdir(current_root)
                if os.path.isdir(
                    os.path.join(current_root, d)
                )
            ]

            if subdirs:
                candidates.append(current_root)

    if not candidates:
        return None

    # Prefer the deepest matching directory
    return max(candidates, key=lambda x: x.count(os.sep))


