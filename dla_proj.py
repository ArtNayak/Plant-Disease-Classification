def build_custom_cnn(
    input_shape=(224, 224, 3),
    num_classes=3
):

    inputs = layers.Input(
        shape=input_shape
    )

    # Augmentation
    x = data_augmentation(inputs)

    # Normalize pixels to [0, 1]
    x = layers.Rescaling(
        1.0 / 255.0
    )(x)

    # --------------------------------------------------------
    # Block 1
    # --------------------------------------------------------

    x = layers.Conv2D(
        32,
        3,
        padding="same",
        activation="relu"
    )(x)

    x = layers.MaxPooling2D()(x)

    # --------------------------------------------------------
    # Block 2
    # --------------------------------------------------------

    x = layers.Conv2D(
        64,
        3,
        padding="same",
        activation="relu"
    )(x)

    x = layers.MaxPooling2D()(x)

    # --------------------------------------------------------
    # Block 3
    # --------------------------------------------------------

    x = layers.Conv2D(
        128,
        3,
        padding="same",
        activation="relu"
    )(x)

    x = layers.MaxPooling2D()(x)

    # --------------------------------------------------------
    # Block 4
    # --------------------------------------------------------

    x = layers.Conv2D(
        256,
        3,
        padding="same",
        activation="relu"
    )(x)

    x = layers.MaxPooling2D()(x)

    # --------------------------------------------------------
    # Classifier
    # --------------------------------------------------------

    x = layers.GlobalAveragePooling2D()(x)

    x = layers.Dense(
        128,
        activation="relu"
    )(x)

    x = layers.Dropout(
        0.4
    )(x)

    outputs = layers.Dense(
        num_classes,
        activation="softmax"
    )(x)

    return Model(
        inputs,
        outputs,
        name="Custom_CNN"
    )


